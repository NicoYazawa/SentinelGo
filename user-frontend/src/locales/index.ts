function detectDefault(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY) as Lang | null
  if (stored && (SUPPORTED_LANGS as Lang[]).includes(stored)) return stored
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

export const i18n = createI18n({
  legacy: false,
  locale: detectDefault(),
  fallbackLocale: 'zh-CN',
  messages,
})

export const currentLang = ref<Lang>(detectDefault())

export function elementLocale(lang: Lang): Language {
  return lang === 'en-US' ? enUS : zhCN
}

export const elLocaleRef = computed(() => elementLocale(currentLang.value))

export function setLocale(lang: Lang): void {
  if (!SUPPORTED_LANGS.includes(lang)) return
  currentLang.value = lang
  i18n.global.locale.value = lang
  localStorage.setItem(STORAGE_KEY, lang)
  document.documentElement.lang = lang
}

document.documentElement.lang = currentLang.value
